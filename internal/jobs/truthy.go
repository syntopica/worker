package jobs

import "encoding/json"

// truthy mirrors the emptiness test the contract was written against: null,
// false, zero and empty strings, lists and objects are absent.
func truthy(value any) bool {
	switch typed := value.(type) {
	case nil:
		return false
	case bool:
		return typed
	case string:
		return typed != ""
	case json.Number:
		number, err := typed.Float64()

		return err != nil || number != 0
	case []any:
		return len(typed) > 0
	case map[string]any:
		return len(typed) > 0
	default:
		return true
	}
}
